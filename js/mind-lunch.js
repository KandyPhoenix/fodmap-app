// Standard MIND recipes are not low FODMAP, so they join the family collection
// (not KANDY_RECIPES, which is auto-tagged 'fodmap'). Each one carries its
// low-FODMAP version in fodmapOption, shown by the recipe's 🍀 toggle.
(function () {
  if (typeof FAMILY_RECIPES !== 'undefined') {
    const seen = new Set(FAMILY_RECIPES.map(r => r.id));
    MIND_LUNCH.forEach(r => { if (!seen.has(r.id)) { FAMILY_RECIPES.push(r); seen.add(r.id); } });
  }
  MIND_LUNCH.forEach(function (r) {
    if (r.nutrition && typeof RECIPE_NUTRITION !== 'undefined') RECIPE_NUTRITION[r.id] = r.nutrition;
  });
})();
